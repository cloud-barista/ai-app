// amdDeviceNames is amdArchitectureIDs keyed the way a lookup needs it.
var amdDeviceNames = func() map[uint64]string {
	names := make(map[uint64]string, 256)
	for label, ids := range amdArchitectureIDs {
		for _, id := range ids {
			names[id] = label
		}
	}

	return names
}()
