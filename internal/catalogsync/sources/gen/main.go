// Command gen writes vllm_archs.go: the model architectures one vLLM release
// lists as supported in vllm/model_executor/models/registry.py.
//
// It reads the dicts that registry.py merges into _VLLM_MODELS and collects
// their keys. Previously supported and out-of-tree architectures are not in
// _VLLM_MODELS and are left out.
//
// Usage, from internal/catalogsync/sources:
//
//	go run ./gen -version v0.32.0 -o vllm_archs.go
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strings"
	"time"
)

const registryURL = "https://raw.githubusercontent.com/vllm-project/vllm/%s/vllm/model_executor/models/registry.py"

var (
	dictStart = regexp.MustCompile(`^(_[A-Z0-9_]+) = \{`)
	mergeLine = regexp.MustCompile(`^\s+\*\*(_[A-Z0-9_]+),`)
	entryLine = regexp.MustCompile(`^    "([A-Za-z0-9_.]+)": \(`)
)

func main() {
	version := flag.String("version", "", "vLLM release tag, such as v0.32.0")
	out := flag.String("o", "vllm_archs.go", "file to write")
	flag.Parse()
	if *version == "" {
		fail(fmt.Errorf("-version is required"))
	}

	url := fmt.Sprintf(registryURL, *version)
	src, err := fetch(url)
	if err != nil {
		fail(err)
	}
	archs, err := parse(src)
	if err != nil {
		fail(err)
	}
	code, err := render(*version, url, archs)
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(*out, code, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("wrote %s: %d architectures from vLLM %s\n", *out, len(archs), *version)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}

func fetch(url string) ([]byte, error) {
	client := &http.Client{Timeout: 60 * time.Second}
	resp, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	return io.ReadAll(io.LimitReader(resp.Body, 16<<20))
}

// parse collects the keys of every dict merged into _VLLM_MODELS.
func parse(src []byte) ([]string, error) {
	keys := map[string][]string{}
	var merged []string
	current := ""
	sc := bufio.NewScanner(bytes.NewReader(src))
	for sc.Scan() {
		line := sc.Text()
		if m := dictStart.FindStringSubmatch(line); m != nil {
			current = m[1]
			continue
		}
		if line == "}" {
			current = ""
			continue
		}
		if current == "" {
			continue
		}
		if current == "_VLLM_MODELS" {
			if m := mergeLine.FindStringSubmatch(line); m != nil {
				merged = append(merged, m[1])
			}
			continue
		}
		if m := entryLine.FindStringSubmatch(line); m != nil {
			keys[current] = append(keys[current], m[1])
		}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if len(merged) == 0 {
		return nil, fmt.Errorf("no dicts merged into _VLLM_MODELS found")
	}
	var archs []string
	for _, dict := range merged {
		if len(keys[dict]) == 0 {
			return nil, fmt.Errorf("dict %s merged into _VLLM_MODELS has no entries", dict)
		}
		archs = append(archs, keys[dict]...)
	}
	slices.Sort(archs)
	return slices.Compact(archs), nil
}

func render(version, url string, archs []string) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by go run ./gen; DO NOT EDIT.\n\n")
	b.WriteString("package sources\n\n")
	fmt.Fprintf(&b, "// VLLMVersion is the vLLM release vllmArchitectures was read from. It must\n")
	fmt.Fprintf(&b, "// match the tag of the vllm runtime image.\n")
	fmt.Fprintf(&b, "const VLLMVersion = %q\n\n", version)
	fmt.Fprintf(&b, "// vllmArchitectures are the model architectures vLLM %s supports: the\n", version)
	fmt.Fprintf(&b, "// keys of the dicts merged into _VLLM_MODELS in\n// %s\n", url)
	b.WriteString("//\n// Regenerate with go generate ./internal/catalogsync/sources after changing\n")
	b.WriteString("// the version in the go:generate line of sources.go.\n")
	b.WriteString("var vllmArchitectures = []string{\n")
	for _, a := range archs {
		fmt.Fprintf(&b, "\t%q,\n", a)
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}
